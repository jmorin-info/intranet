/**
 * AI UX Engine — Type Definitions
 *
 * Deterministic, rules-based prediction system.
 * No ML, no external API — pure heuristic intelligence.
 */

import type { UIEntity, UIEventType } from '@/lib/events';

/** A tracked user action in the current session */
export interface TrackedAction {
  entity: UIEntity;
  eventType: UIEventType;
  entityId: string;
  timestamp: number;
  module: string;
}

/** Aggregated behavioral profile for the current session */
export interface BehaviorProfile {
  /** Count of each action type performed this session */
  actionCounts: Record<string, number>;
  /** Last N entity IDs viewed or mutated */
  recentEntityIds: string[];
  /** Last N modules visited */
  recentModules: string[];
  /** Detected pattern flags */
  patterns: {
    burstMode: boolean;
    repeatedStatusChanges: number;
    contextSwitchCount: number;
  };
}

/** A suggestion generated by the heuristic engine */
export interface AISuggestion {
  id: string;
  type: 'ACTION' | 'NAVIGATION' | 'BULK' | 'SHORTCUT';
  label: string;
  /** 0.0 to 1.0 — suggestions below 0.6 are not shown */
  confidence: number;
  /** Target entity type (optional) */
  entity?: UIEntity;
  /** Icon name from lucide-react */
  icon?: string;
  /** Route to navigate to when clicked */
  href?: string;
  /** Callback to execute when clicked (alternative to href) */
  action?: () => void;
}

/** Session-level AI context */
export interface AIContext {
  /** Ring buffer of tracked actions (max 30) */
  actions: TrackedAction[];
  /** Current behavioral profile (recomputed on every action) */
  profile: BehaviorProfile;
  /** Active module the user is currently viewing */
  activeModule: string;
  /** Generated suggestions (recomputed after profile update) */
  suggestions: AISuggestion[];
  /** Timestamp of last suggestion update */
  lastSuggestionUpdate: number;
}
